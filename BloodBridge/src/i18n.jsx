function readLang() {
  try {
    const saved = localStorage.getItem(LANG_KEY)
    if (saved === 'ar' || saved === 'en') return saved
  } catch {
    /* ignore */
  }
  if (typeof navigator !== 'undefined' && navigator.language?.toLowerCase().startsWith('ar')) return 'ar'
  return 'en'
}

function fill(template, vars, lang) {
  return template.replace(/\{(\w+)\}/g, (_, key) => {
    const value = vars?.[key]
    if (value == null) return ''
    if (key === 'city') return copy[lang][`city.${value}`] || String(value)
    if ((key === 'place' || key === 'org' || key === 'reason') && lang === 'ar') return LEGACY[value] || String(value)
    return String(value)
  })
}

const LanguageContext = createContext(null)

export function LanguageProvider({ children }) {
  const [lang, setLangState] = useState(readLang)
  setActiveLang(lang)

  useEffect(() => {
    document.documentElement.lang = lang
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr'
    try {
      localStorage.setItem(LANG_KEY, lang)
    } catch {
      /* ignore */
    }
  }, [lang])

  const api = useMemo(() => {
    function t(key, vars) {
      const template = copy[lang][key] ?? copy.en[key] ?? key
      return vars ? fill(template, vars, lang) : template
    }
    function phrase(text) {
      if (!text) return ''
      if (lang !== 'ar') return text
      return LEGACY[text] || text
    }
    function tx(error) {
      if (!error) return ''
      if (copy[lang][error]) return t(error)
      return phrase(error)
    }
    function cityName(name) {
      return copy[lang][`city.${name}`] || name
    }
    function nText(n, kind) {
      const count = Number(n) || 0
      const form = count === 1 ? 'one' : count === 2 ? 'two' : 'many'
      return t(`n.${kind}.${form}`, { n: count })
    }
    function needLine(hospital, units, group) {
      const safeGroup = `\u2066${group || ''}\u2069`
      return t('need.line', { hospital: hospital || '', units: nText(units, 'bag'), group: safeGroup })
    }
    function wave(note) {
      if (!note) return ''
      if (typeof note === 'string') return phrase(note)
      const count = Number(note.count) || 0
      const form = count === 1 ? 'one' : count === 2 ? 'two' : 'many'
      return t(note.key, { count, people: t(`wave.people.${form}`), where: note.where ? t(`wave.where.${note.where}`) : '' })
    }
    function noteTitle(note) {
      if (note.titleKey && copy[lang][note.titleKey]) return t(note.titleKey, note.vars)
      return phrase(note.title)
    }
    function noteBody(note) {
      if (note.bodyKey && copy[lang][note.bodyKey]) return t(note.bodyKey, note.vars)
      return phrase(note.body)
    }
    function reasonText(value) {
      if (!value) return ''
      if (copy[lang][`reason.${value}`]) return t(`reason.${value}`)
      return phrase(value)
    }
    function setLang(next) {
      setLangState(next === 'ar' ? 'ar' : 'en')
    }
    return { lang, setLang, t, phrase, tx, cityName, nText, needLine, wave, noteTitle, noteBody, reasonText }
  }, [lang])

  return <LanguageContext.Provider value={api}>{children}</LanguageContext.Provider>
}

// eslint-disable-next-line react-refresh/only-export-components
export function useI18n() {
  const value = useContext(LanguageContext)
  if (!value) throw new Error('useI18n must be used inside LanguageProvider')
  return value
}

export function LangSwitch() {
  const { lang, setLang } = useI18n()
  return (
    <div className="inline-flex rounded-full bg-ivory p-1 shadow-sm ring-1 ring-line" role="group" aria-label={lang === 'ar' ? 'اللغة' : 'Language'}>
      <button
        type="button"
        onClick={() => setLang('ar')}
        aria-pressed={lang === 'ar'}
        className={`rounded-full px-3 py-2 text-sm font-medium transition duration-200 ${lang === 'ar' ? 'bg-wine text-white shadow-sm' : 'text-ink hover:bg-blush'}`}
      >
        عربي
      </button>
      <button
        type="button"
        onClick={() => setLang('en')}
        aria-pressed={lang === 'en'}
        className={`rounded-full px-3 py-2 text-sm font-medium transition duration-200 ${lang === 'en' ? 'bg-wine text-white shadow-sm' : 'text-ink hover:bg-blush'}`}
      >
        English
      </button>
    </div>
  )
}
